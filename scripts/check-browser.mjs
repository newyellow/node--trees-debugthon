  assert.ok(await page.getByRole('checkbox', { name: '顯示公園、綠地與廣場', exact: true }).isDisabled());
  await page.screenshot({ path: 'test-results/density-desktop.png' });
  const street = JSON.parse(await readFile(new URL('../public/data/street-trees.geojson', import.meta.url)));
  const distance = f => (f.geometry.coordinates[0] - 121.542) ** 2 + (f.geometry.coordinates[1] - 25.048) ** 2;
  const nearCenter = street.features.reduce((nearest, feature) => distance(feature) < distance(nearest) ? feature : nearest);
  assert.ok(nearCenter);
  const meters = toMeters(nearCenter.geometry.coordinates);
  const cellCenter = toLngLat(meters.map(value => (Math.floor(value / 250) + 0.5) * 250));
  const cellPoint = await page.locator('.leaflet-tile-loaded').first().evaluate((tile, coordinate) => {
    const [z, tileX, tileY] = new URL(tile.src).pathname.split('/').slice(1).map(v => Number.parseInt(v));
    const [lng, lat] = coordinate, scale = 256 * 2 ** z;
    const sin = Math.sin(lat * Math.PI / 180), rect = tile.getBoundingClientRect();
    return { x: rect.x + ((lng + 180) / 360 * scale - tileX * 256) * rect.width / 256, y: rect.y + ((0.5 - Math.log((1 + sin) / (1 - sin)) / (4 * Math.PI)) * scale - tileY * 256) * rect.height / 256 };
  }, cellCenter);
  await page.mouse.click(cellPoint.x, cellPoint.y);
  await page.locator('.density-popup').waitFor();
  assert.ok((await page.locator('.density-popup').textContent()).includes('250 × 250'));
  await page.keyboard.press('Escape');
  await page.selectOption('#grid-size', '500');
  await page.waitForFunction(() => document.querySelector('#cell-area').textContent.includes('25 公頃'));
  await page.locator('#heat-opacity').fill('0.4');
  await page.selectOption('#district', '大安區');
  await page.waitForFunction(() => document.querySelector('#map-title').textContent.includes('大安區'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  await page.locator('#fit-data').click();
  await page.waitForFunction(() => Number(document.querySelector('#visible-count').textContent.replaceAll(',', '')) > 0 && Number(document.querySelector('#density-legend').dataset.cells) > 0);
  await page.waitForTimeout(400);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: 'test-results/density-mobile.png', fullPage: true });
  await page.locator('#search').fill('NO_MATCH_123456');
  await page.locator('#search').press('Enter');
  await page.waitForFunction(() => document.querySelector('#density-legend').dataset.cells === '0');
  assert.equal(await page.locator('#visible-count').textContent(), '0');
  await page.locator('#reset-map').click();
  await page.locator('#clear-layers').click();
  await page.waitForFunction(() => document.querySelector('#map-notice').textContent.includes('請勾選'));
  await page.locator('#point-mode').click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  assert.ok(await page.getByRole('checkbox', { name: '顯示公園、綠地與廣場', exact: true }).isEnabled());
  console.log('PASS: density mode, tree-only counts, metric cell popup, grid size, opacity, district, empty search, empty layers, mobile layout, and point-mode restoration.');
