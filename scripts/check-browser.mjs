import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';

const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('test-results', { recursive: true });
try {
  await page.goto(process.env.PREVIEW_URL ?? 'http://127.0.0.1:5173/');
  await page.waitForFunction(() => document.querySelector('#map-notice').textContent.includes('全覽模式'));
  assert.equal(await page.locator('.layer-card').count(), 5);
  assert.ok(Number((await page.locator('#visible-count').textContent()).replaceAll(',', '')) > 0);
  for (const checkbox of await page.locator('.layer-label input').all()) await checkbox.check();
  await page.waitForFunction(() => document.querySelector('#active-count').textContent === '5' && !document.querySelector('#layers').textContent.includes('載入中'));
  await page.selectOption('#district', '中正區');
  await page.waitForFunction(() => document.querySelector('#map-title').textContent.includes('中正區'));
  assert.ok(Number((await page.locator('#count-sidewalks').textContent()).replace(/[^0-9]/g, '')) > 0);
  await page.locator('#reset-map').click();
  await page.locator('#clear-layers').click();
  await page.getByRole('checkbox', { name: '顯示公園、綠地與廣場', exact: true }).check();
  await page.locator('#search').fill('大安森林公園');
  await page.locator('#search').press('Enter');
  await page.waitForTimeout(700);
  assert.ok(Number((await page.locator('#visible-count').textContent()).replaceAll(',', '')) > 0);
  const parks = JSON.parse(await readFile(new URL('../public/data/parks.geojson', import.meta.url)));
  const target = parks.features.find(feature => feature.properties.pm_name === '大安森林公園');
  const point = await page.locator('.leaflet-tile-loaded').first().evaluate((tile, coordinate) => {
    const [z, tileX, tileY] = new URL(tile.src).pathname.split('/').slice(1).map(v => Number.parseInt(v));
    const [lng, lat] = coordinate, scale = 256 * 2 ** z;
    const sin = Math.sin(lat * Math.PI / 180);
    const x = (lng + 180) / 360 * scale;
    const y = (0.5 - Math.log((1 + sin) / (1 - sin)) / (4 * Math.PI)) * scale;
    const rect = tile.getBoundingClientRect();
    return { x: rect.x + x - tileX * 256, y: rect.y + y - tileY * 256 };
  }, target.geometry.coordinates);
  await page.screenshot({ path: 'test-results/search.png' });
  await page.mouse.click(point.x, point.y);
  await page.waitForSelector('.feature-popup');
  assert.ok((await page.locator('.feature-popup').textContent()).includes('大安森林公園'));
  await page.keyboard.press('Escape');
  await page.locator('#reset-map').click();
  for (const checkbox of await page.locator('.layer-label input').all()) await checkbox.check();
  await page.locator('#about-button').click();
  assert.equal(await page.locator('dialog[open]').count(), 1);
  assert.equal(await page.locator('.quality-row').count(), 5);
  await page.locator('#close-dialog').click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'test-results/desktop.png' });
  await page.locator('#clear-layers').click();
  assert.equal(await page.locator('#visible-count').textContent(), '0');
  assert.equal(await page.locator('.cluster').count(), 0);
  await page.getByRole('checkbox', { name: '顯示公園、綠地與廣場', exact: true }).check();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: real-data loading, five layers, district polygons, keyword search, feature popup, reset, data report, clear, and mobile layout.');
  console.log('Screenshots: test-results/desktop.png, test-results/mobile.png');
  console.log(`Base map visible: ${await page.locator('.leaflet-tile-loaded').count() > 0}`);
  const failurePage = await browser.newPage();
  await failurePage.route('**/data/street-trees.geojson', route => route.fulfill({ status: 503, body: 'Unavailable' }));
  await failurePage.goto('http://127.0.0.1:5173/');
  await failurePage.getByRole('button', { name: '重試', exact: true }).waitFor();
  await failurePage.unroute('**/data/street-trees.geojson');
  await failurePage.getByRole('button', { name: '重試', exact: true }).click();
  await failurePage.waitForFunction(() => !document.querySelector('#layers').textContent.includes('載入失敗') && !document.querySelector('#layers').textContent.includes('載入中'));
  console.log('PASS: layer fetch failure and retry recovery.');
} finally { await browser.close(); }
