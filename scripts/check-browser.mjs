  const point = await page.locator('.leaflet-tile-loaded').first().evaluate((tile, coordinate) => {
    const [z, tileX, tileY] = new URL(tile.src).pathname.split('/').slice(1).map(v => Number.parseInt(v));
    const [lng, lat] = coordinate, scale = 256 * 2 ** z;
    const sin = Math.sin(lat * Math.PI / 180);
    const x = (lng + 180) / 360 * scale;
    const y = (0.5 - Math.log((1 + sin) / (1 - sin)) / (4 * Math.PI)) * scale;
    const rect = tile.getBoundingClientRect();
    return { x: rect.x + (x - tileX * 256) * rect.width / 256, y: rect.y + (y - tileY * 256) * rect.height / 256 };
  }, target.geometry.coordinates);
  await page.screenshot({ path: 'test-results/search.png' });
  await page.mouse.click(point.x, point.y);
  await page.waitForSelector('.feature-popup');
